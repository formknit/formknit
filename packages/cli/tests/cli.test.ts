import {
  address, calculated, checkbox, checkboxGroup, columns, dateRange, form, lookup, number, panel, repeater, select, text,
} from '@formknit/core'
import { describe, expect, it } from 'vitest'
import { main, schemaToTypes, typeName, type Io } from '../src'

const invoice = form('Fee invoice', [
  text('rollNumber').label('Roll number'),
  select('country', { NP: 'Nepal', IN: 'India' }),
  panel('Contact', [columns([checkbox('agree')], [checkboxGroup('days', { mon: 'Mon', tue: 'Tue' })])]),
  dateRange('term'),
  address('home'),
  lookup('studentName', { source: 'students', matchField: 'rollNo', matchValue: 'rollNumber' }),
  repeater('items', [text('name'), number('qty'), calculated('amount', 'qty * 2')]),
  calculated('total', 'SUM(items.amount)'),
])

function fakeIo(files: Record<string, string> = {}) {
  const out: string[] = []
  const err: string[] = []
  const written: Record<string, string> = {}
  const io: Io = {
    read: async (path) => {
      if (!(path in files)) throw new Error('missing')
      return files[path]
    },
    write: async (path, content) => void (written[path] = content),
    out: (line) => void out.push(line),
    err: (line) => void err.push(line),
  }
  return { io, out, err, written }
}

describe('type generation', () => {
  it('writes an interface for a schema', () => {
    expect(schemaToTypes(invoice)).toBe(`// Generated by formknit. Do not edit by hand; regenerate when the form changes.
export interface FeeInvoice {
  /** Roll number */
  rollNumber: string
  country: "NP" | "IN" | ''
  agree: boolean
  days: ("mon" | "tue")[]
  term: { start: string; end: string } | null
  home: { line1: string; line2: string; city: string; region: string; postcode: string; country: string } | null
  studentName: unknown
  items: {
    name: string
    qty: number | null
    amount: number | string | boolean | null
  }[]
  total: number | string | boolean | null
}
`)
  })

  it('makes a usable type name', () => {
    expect(typeName('fee invoice 2027')).toBe('FeeInvoice2027')
    expect(typeName('2027 intake')).toBe('Intake')
    expect(typeName('—')).toBe('FormData')
    expect(typeName(undefined)).toBe('FormData')
  })
})

describe('command line', () => {
  const good = JSON.stringify(invoice)
  const bad = JSON.stringify({ version: 1, pages: [{ key: 'p', components: [{ type: 'text' }, { type: 'select', key: 'pick' }] }] })

  it('checks a schema', async () => {
    const ok = fakeIo({ 'a.json': good })
    expect(await main(['check', 'a.json'], ok.io)).toBe(0)
    expect(ok.out).toEqual(['a.json: no problems'])

    const failing = fakeIo({ 'b.json': bad })
    expect(await main(['check', 'b.json'], failing.io)).toBe(1)
    expect(failing.out).toEqual([
      'b.json: 1 error, 1 warning',
      '  error    #0: A text field needs a key',
      '  warning  pick: Select field has no options',
    ])
  })

  it('generates types to the screen or a file', async () => {
    const screen = fakeIo({ 'a.json': good })
    expect(await main(['types', 'a.json', '--name', 'Invoice'], screen.io)).toBe(0)
    expect(screen.out[0]).toContain('export interface Invoice {')

    const file = fakeIo({ 'a.json': good })
    expect(await main(['types', 'a.json', '-o', 'invoice.ts'], file.io)).toBe(0)
    expect(file.written['invoice.ts']).toContain('export interface FeeInvoice {')
    expect(file.out).toEqual(['Wrote invoice.ts'])
  })

  it('refuses to generate types for a broken schema, and explains bad input', async () => {
    const broken = fakeIo({ 'b.json': bad })
    expect(await main(['types', 'b.json'], broken.io)).toBe(1)
    expect(broken.err[0]).toMatch(/has errors/)

    const missing = fakeIo()
    expect(await main(['check', 'nope.json'], missing.io)).toBe(1)
    expect(missing.err).toEqual(['Cannot read nope.json'])

    const notJson = fakeIo({ 'c.json': '{' })
    expect(await main(['check', 'c.json'], notJson.io)).toBe(1)
    expect(notJson.err[0]).toMatch(/not valid JSON/)

    const help = fakeIo()
    expect(await main([], help.io)).toBe(0)
    expect(help.out[0]).toMatch(/^Usage:/)
    expect(await main(['frobnicate', 'x'], help.io)).toBe(1)
  })
})
