import { checkSchema, getField, type ComponentSchema, type FormSchema, type SchemaIssue } from '@formknit/core'
import { readFile, writeFile } from 'node:fs/promises'

const TEXT = new Set(['text', 'textarea', 'richText', 'email', 'phone', 'url', 'date', 'time', 'signature'])
const NUMBER = new Set(['number', 'rating', 'slider'])
const BOOLEAN = new Set(['checkbox', 'toggle'])
const literal = (value: string) => JSON.stringify(value)
const property = (key: string) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : literal(key))

function typeOf(c: ComponentSchema, indent: string): string {
  if (TEXT.has(c.type)) return 'string'
  if (NUMBER.has(c.type)) return 'number | null'
  if (BOOLEAN.has(c.type)) return 'boolean'
  const choices = (c.options ?? []).map((o) => literal(String(o.value)))
  if (c.type === 'select' || c.type === 'radio') return [...choices, "''"].join(' | ')
  if (c.type === 'checkboxGroup') return choices.length ? `(${choices.join(' | ')})[]` : 'string[]'
  if (c.type === 'calculated') return 'number | string | boolean | null'
  if (c.type === 'dateRange') return '{ start: string; end: string } | null'
  if (c.type === 'address') return '{ line1: string; line2: string; city: string; region: string; postcode: string; country: string } | null'
  if (c.type === 'file') return '{ name: string; size: number; type: string; url?: string } | null'
  if (c.type === 'repeater') return `{\n${members(c.components, `${indent}  `)}${indent}}[]`
  // Lookups, hidden fields and custom types can hold anything.
  return 'unknown'
}

function members(list: ComponentSchema[] | undefined, indent: string): string {
  let out = ''
  for (const c of list ?? []) {
    const kind = getField(c.type)?.kind
    if (c.key && (kind === 'input' || kind === 'calculated' || kind === 'repeater')) {
      if (c.label) out += `${indent}/** ${c.label.replace(/\*\//g, '* /')} */\n`
      out += `${indent}${property(c.key)}: ${typeOf(c, indent)}\n`
      continue
    }
    // Panels and columns do not nest the data; their fields belong to the same object.
    out += members(c.components, indent)
    for (const col of c.columns ?? []) out += members(col.components, indent)
  }
  return out
}

/** "fee invoice" -> "FeeInvoice", for use as a type name. */
export function typeName(title: string | undefined, fallback = 'FormData'): string {
  const words = (title ?? '').match(/[A-Za-z0-9]+/g) ?? []
  const name = words.map((w) => w[0].toUpperCase() + w.slice(1)).join('').replace(/^\d+/, '')
  return name || fallback
}

/**
 * Writes a TypeScript interface for the data a schema produces. Fields that may be hidden
 * are still listed: a hidden field is simply absent from a submission, so treat every
 * conditional field as possibly undefined when reading stored data.
 */
export function schemaToTypes(schema: FormSchema, name = typeName(schema.title)): string {
  let body = ''
  for (const page of schema.pages ?? []) body += members(page.components, '  ')
  return `// Generated by formknit. Do not edit by hand; regenerate when the form changes.\nexport interface ${name} {\n${body}}\n`
}

export interface Io {
  read: (path: string) => Promise<string>
  write: (path: string, content: string) => Promise<void>
  out: (line: string) => void
  err: (line: string) => void
}

const nodeIo: Io = {
  read: (path) => readFile(path, 'utf8'),
  write: (path, content) => writeFile(path, content),
  out: (line) => console.log(line),
  err: (line) => console.error(line),
}

const HELP = `Usage:
  formknit check <schema.json>                     List problems in a form schema
  formknit types <schema.json> [-o out.ts] [-n Name]  Generate a TypeScript type for its data

check exits with 1 when the schema has errors (warnings alone exit with 0).`

async function load(path: string, io: Io): Promise<FormSchema | null> {
  let text: string
  try {
    text = await io.read(path)
  } catch {
    io.err(`Cannot read ${path}`)
    return null
  }
  try {
    return JSON.parse(text)
  } catch (e) {
    io.err(`${path} is not valid JSON: ${e instanceof Error ? e.message : String(e)}`)
    return null
  }
}

const describe = (issue: SchemaIssue) => `  ${issue.level === 'error' ? 'error  ' : 'warning'}  ${issue.path}: ${issue.message}`

/** Runs the command line. Returns the exit code. */
export async function main(args: string[], io: Io = nodeIo): Promise<number> {
  const [command, file, ...rest] = args
  if (!command || command === 'help' || command === '--help' || command === '-h') {
    io.out(HELP)
    return 0
  }
  if ((command !== 'check' && command !== 'types') || !file) {
    io.err(HELP)
    return 1
  }
  const schema = await load(file, io)
  if (!schema) return 1
  const issues = checkSchema(schema)
  const errors = issues.filter((i) => i.level === 'error')

  if (command === 'check') {
    if (!issues.length) io.out(`${file}: no problems`)
    else {
      io.out(`${file}: ${errors.length} ${errors.length === 1 ? 'error' : 'errors'}, ${issues.length - errors.length} ${issues.length - errors.length === 1 ? 'warning' : 'warnings'}`)
      for (const issue of issues) io.out(describe(issue))
    }
    return errors.length ? 1 : 0
  }

  if (errors.length) {
    io.err(`${file} has errors; fix them before generating types:`)
    for (const issue of errors) io.err(describe(issue))
    return 1
  }
  const flag = (short: string, long: string) => {
    const at = rest.findIndex((a) => a === short || a === long)
    return at >= 0 ? rest[at + 1] : undefined
  }
  const output = schemaToTypes(schema, flag('-n', '--name'))
  const target = flag('-o', '--out')
  if (target) {
    await io.write(target, output)
    io.out(`Wrote ${target}`)
  } else io.out(output)
  return 0
}
