// ---------- Email ----------
export interface Mail {
  to: string
  subject: string
  text: string
}
/** Hands a message to whatever actually sends email (SMTP, a provider's API). Throw to report failure. */
export type Transport = (mail: Mail) => Promise<void>

/**
 * Records every email in the outbox table, then passes it to the transport. With no transport
 * (the default in development) the email is only recorded, so nothing leaves the machine.
 */
export function createMailer(db: Db, transport?: Transport) {
  return async (mail: Mail): Promise<void> => {
    const id = newId()
    db.insert(outbox).values({ id, toAddress: mail.to, subject: mail.subject, body: mail.text, createdAt: Date.now() }).run()
    if (!transport) return
    try {
      await transport(mail)
      db.update(outbox).set({ sentAt: Date.now() }).where(eq(outbox.id, id)).run()
    } catch (e) {
      db.update(outbox).set({ error: e instanceof Error ? e.message : String(e) }).where(eq(outbox.id, id)).run()
    }
  }
}

// ---------- Webhooks ----------
const PRIVATE_V4 = [/^10\./, /^127\./, /^169\.254\./, /^172\.(1[6-9]|2\d|3[01])\./, /^192\.168\./, /^0\./]

/**
 * Whether we are willing to send a webhook to this address. On a hosted service a webhook
 * must not be usable to reach machines on the server's own network. This checks the address
 * as written; it does not defend against a public name that later resolves to a private
 * address, which needs a check at connection time.
 */
export function webhookUrlProblem(raw: string, allowPrivate: boolean): string | null {
  let url: URL
  try {
    url = new URL(raw)
  } catch {
    return 'Enter a full address, such as https://example.com/hook'
  }
  if (url.protocol !== 'https:' && url.protocol !== 'http:') return 'The address must start with https://'
  if (url.username || url.password) return 'The address must not contain a user name or password'
  if (allowPrivate) return null
  if (url.protocol !== 'https:') return 'The address must start with https://'
  const host = url.hostname.replace(/^\[|\]$/g, '').toLowerCase()
  if (host === 'localhost' || host.endsWith('.localhost') || host.endsWith('.local') || host.endsWith('.internal')) return 'That address is on a private network'
  if (isIP(host) === 4 && PRIVATE_V4.some((re) => re.test(host))) return 'That address is on a private network'
  if (isIP(host) === 6 && (host === '::1' || host.startsWith('fc') || host.startsWith('fd') || host.startsWith('fe80') || host.startsWith('::ffff:'))) {
    return 'That address is on a private network'
  }
  return null
}

export const sign = (secret: string, body: string) => `sha256=${createHmac('sha256', secret).update(body).digest('hex')}`

/** Sends one webhook and records how it went. Never throws. */
export async function deliver(db: Db, fetcher: typeof fetch, hook: { id: string; url: string; secret: string }, event: string, payload: unknown) {
  const body = JSON.stringify({ event, sentAt: new Date().toISOString(), ...(payload as object) })
  let ok = false
  let statusCode: number | null = null
  let error: string | null = null
  try {
    const res = await fetcher(hook.url, {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'user-agent': 'Formknit-Webhook', 'x-formknit-event': event, 'x-formknit-signature': sign(hook.secret, body) },
      body,
      redirect: 'error',
      signal: AbortSignal.timeout(5000),
    })
    statusCode = res.status
    ok = res.ok
    if (!ok) error = `The receiver answered ${res.status}`
  } catch (e) {
    error = e instanceof Error ? e.message : String(e)
  }
  db.insert(deliveries).values({ id: newId(), webhookId: hook.id, event, ok, statusCode, error, createdAt: Date.now() }).run()
  return { ok, statusCode, error }
}

// ---------- File storage ----------
export interface Storage {
  save(id: string, bytes: Uint8Array): Promise<void>
  read(id: string): Promise<Uint8Array | null>
  remove(id: string): Promise<void>
}

/** Keeps uploads in a folder on this machine. Ids are generated by us, never taken from the upload. */
export function diskStorage(dir: string): Storage {
  const path = (id: string) => join(dir, id.replace(/[^a-zA-Z0-9-]/g, ''))
  return {
    async save(id, bytes) {
      await mkdir(dir, { recursive: true })
      await writeFile(path(id), bytes)
    },
    read: (id) => readFile(path(id)).then((b) => new Uint8Array(b), () => null),
    remove: (id) => unlink(path(id)).catch(() => {}),
  }
}

export function memoryStorage(): Storage & { items: Map<string, Uint8Array> } {
  const items = new Map<string, Uint8Array>()
  return {
    items,
    save: async (id, bytes) => void items.set(id, bytes),
    read: async (id) => items.get(id) ?? null,
    remove: async (id) => void items.delete(id),
  }
}

/** Finds a field anywhere in a schema, including inside repeaters. */
export function findField(schema: FormSchema, key: string): ComponentSchema | undefined {
  let found: ComponentSchema | undefined
  const visit = (list: ComponentSchema[] | undefined) => {
    for (const c of list ?? []) {
      if (c.key === key) found = found ?? c
      visit(c.components)
      for (const col of c.columns ?? []) visit(col.components)
    }
  }
  for (const page of schema.pages ?? []) visit(page.components)
  return found
}

// ---------- Reports ----------
const DAY = 86400000
const dayKey = (ms: number) => new Date(ms).toISOString().slice(0, 10)

/** Submissions per day for the last `days` days, oldest first, with empty days included. */
export function dailySeries(times: number[], days: number, now = Date.now()): { day: string; count: number }[] {
  const counts = new Map<string, number>()
  for (const t of times) counts.set(dayKey(t), (counts.get(dayKey(t)) ?? 0) + 1)
  return Array.from({ length: days }, (_, i) => {
    const day = dayKey(now - (days - 1 - i) * DAY)
    return { day, count: counts.get(day) ?? 0 }
  })
}

const CHOICE = new Set(['select', 'radio', 'checkboxGroup'])
const BOOLEAN = new Set(['checkbox', 'toggle'])
const NUMERIC = new Set(['number', 'rating', 'slider', 'calculated'])

export interface FieldReport {
  key: string
  label: string
  kind: 'choices' | 'numbers'
  answered: number
  /** For choices: how many picked each option. */
  counts?: { label: string; count: number }[]
  /** For numbers. */
  average?: number
  min?: number
  max?: number
  sum?: number
}

/** Summarises the answers to each top-level choice or number field. */
export function buildReport(schema: FormSchema, rows: { data: Record<string, unknown>; status: Status; createdAt: number }[], now = Date.now()) {
  const fields: FieldReport[] = []
  const visit = (list: ComponentSchema[] | undefined) => {
    for (const c of list ?? []) {
      const kind = getField(c.type)?.kind
      if (kind === 'layout') {
        visit(c.components)
        for (const col of c.columns ?? []) visit(col.components)
        continue
      }
      if (!c.key || c.type === 'repeater') continue
      const values = rows.map((r) => r.data[c.key!])
      const label = c.label || c.key
      if (CHOICE.has(c.type) || BOOLEAN.has(c.type)) {
        const options = BOOLEAN.has(c.type) ? [{ label: 'Yes', value: 'true' }, { label: 'No', value: 'false' }] : (c.options ?? [])
        const counts = options.map((o) => ({
          label: o.label,
          count: values.filter((v) => (Array.isArray(v) ? v.map(String).includes(String(o.value)) : String(v ?? '') === String(o.value))).length,
        }))
        const answered = values.filter((v) => (Array.isArray(v) ? v.length > 0 : v !== undefined && v !== null && v !== '')).length
        fields.push({ key: c.key, label, kind: 'choices', answered, counts })
      } else if (NUMERIC.has(c.type)) {
        const numbers = values.filter((v): v is number => typeof v === 'number' && Number.isFinite(v))
        if (!numbers.length) {
          fields.push({ key: c.key, label, kind: 'numbers', answered: 0 })
          continue
        }
        const sum = numbers.reduce((a, b) => a + b, 0)
        fields.push({
          key: c.key, label, kind: 'numbers', answered: numbers.length, sum: Number(sum.toPrecision(15)),
          average: Number((sum / numbers.length).toPrecision(12)), min: Math.min(...numbers), max: Math.max(...numbers),
        })
      }
    }
  }
  for (const page of schema.pages ?? []) visit(page.components)
  return {
    total: rows.length,
    byStatus: Object.fromEntries(STATUSES.map((s) => [s, rows.filter((r) => r.status === s).length])) as Record<Status, number>,
    series: dailySeries(rows.map((r) => r.createdAt), 30, now),
    fields,
  }
}
